#!/usr/bin/env node
// AssayLint command line. Uses the same engine as the web app (web/core.js).
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { basename, join } from "node:path";
import * as C from "./web/core.js";
import * as R from "./web/report.js";
import { demoFiles } from "./web/demo.js";

const USAGE = `AssayLint ${C.APP_VERSION}
Usage:
  node cli.mjs <results.csv> [options]
    --amp <file>            amplification curves
    --melt <file>           melt curves (enables melt checks)
    --melt-values <type>    derivative | fluorescence (default: detected)
    --map <file>            plate-map template to apply
    --plate-size <96|384>   plate layout for files that number wells 1..N without positions
    --expect <list>         controls expected per target, e.g. ntc,positive,nrt (default: ntc)
    --set key=value         override a rule-set value, e.g. --set sdThreshold=0.5 (repeatable)
    --report <file.html>    write the human-readable report
    --json <file.json>      write structured results
    --wells <file.csv>      write normalised well data
    --packet <file.json>    write the experiment packet
  node cli.mjs --write-demo <dir>   write the synthetic demo files
  node cli.mjs --rules-md           print the rule catalog as Markdown
Exit codes: 0 analysed (findings do not change the exit code), 1 input could not be parsed, 2 usage error.`;

const args = process.argv.slice(2);
const opt = (name, multi = false) => {
  const vals = [];
  for (let i = 0; i < args.length; i++) if (args[i] === name) { vals.push(args[i + 1]); args.splice(i, 2); i--; }
  return multi ? vals : vals.at(-1);
};
const fail = (msg, code = 2) => { console.error(msg); process.exit(code); };

if (args[0] === "--rules-md") {
  const lines = [`# AssayLint rule catalog (rules v${Object.values(C.RULES)[0].version})`, "",
    `Scientific review status: ${C.RULES_REVIEW.status}.`, "", "Generated by `node cli.mjs --rules-md`. Severity belongs to the rule, not a generic score.", "",
    "| Rule | Group | Category | Severity | What is checked | Why it matters |", "|---|---|---|---|---|---|",
    ...Object.entries(C.RULES).map(([id, r]) => `| \`${id}\` | ${r.group} | ${C.CATEGORY_LABEL[r.category]} | ${id === "missing_metadata" ? "per field (see below)" : id === "ntc_amplification" ? "high below the NTC threshold, otherwise medium" : r.severity} | ${r.checks} | ${r.why} |`),
    "", "## Method metadata fields", "", "| Field | Reported when empty as |", "|---|---|",
    ...C.CONTEXT_FIELDS.map(f => `| ${f.label} | ${f.severity ?? "not reported"} |`),
    "", "## Default rule set (placeholders, not expert-reviewed)", "", "| Setting | Default |", "|---|---|",
    ...C.RULESET_FIELDS.map(f => `| ${f.label} | ${C.DEFAULT_PROFILE.values[f.key]} |`), ""];
  console.log(lines.join("\n"));
  process.exit(0);
}
if (args[0] === "--write-demo") {
  const dir = args[1] || fail(USAGE);
  mkdirSync(dir, { recursive: true });
  const f = demoFiles();
  for (const [name, text] of [["demo_results.csv", f.results], ["demo_amplification.csv", f.amp], ["demo_melt_derivative.csv", f.melt]]) writeFileSync(join(dir, name), text);
  console.log(`Wrote demo files to ${dir}`);
  process.exit(0);
}

const plateSize = Number(opt("--plate-size")) || undefined;
const ampPath = opt("--amp"), meltPath = opt("--melt"), meltValues = opt("--melt-values"), mapPath = opt("--map"), expect = opt("--expect");
const sets = opt("--set", true), out = { report: opt("--report"), json: opt("--json"), wells: opt("--wells"), packet: opt("--packet") };
if (args.length !== 1 || args[0].startsWith("--")) fail(USAGE);
const input = args[0];

const read = p => { try { return readFileSync(p, "utf8"); } catch (e) { fail(`Cannot read ${p}: ${e.message}`, 1); } };
const actor = process.env.USER || process.env.USERNAME || "cli";
const exp = C.newExperiment({ title: basename(input) }, actor);
try {
  const text = read(input), parsed = C.parseResults(text, { plateSize });
  exp.source = C.fileRecord({ name: basename(input), text, sha: await C.sha256(text), actor, format: parsed.format, plateSize: plateSize || null });
  for (const w of parsed.warnings) console.log(`Note: ${w}`);
  if (ampPath) { const t = read(ampPath); C.parseCurves(t, "amp"); exp.amp = C.fileRecord({ name: basename(ampPath), text: t, sha: await C.sha256(t), actor }); }
  if (meltPath) {
    const t = read(meltPath), m = C.parseCurves(t, "melt");
    exp.melt = C.fileRecord({ name: basename(meltPath), text: t, sha: await C.sha256(t), actor, valueType: meltValues || m.guessedValueType });
    exp.ruleset.values.meltChecks = true;
  }
} catch (e) {
  if (e instanceof C.ParseError) fail(`Cannot parse input; no checks were run. ${e.message}` + (e.details?.needsPlateSize ? "\nRe-run with --plate-size 96 or --plate-size 384." : "") + (e.details?.headers ? `\nColumns found: ${e.details.headers.join(", ")}` : ""), 1);
  throw e;
}
if (expect) { const s = new Set(expect.split(",").map(x => x.trim())); Object.assign(exp.ruleset.values, { expectNtc: s.has("ntc"), expectPositive: s.has("positive"), expectNrt: s.has("nrt") }); }
for (const kv of sets) {
  const [k, v] = String(kv).split("="), f = C.RULESET_FIELDS.find(x => x.key === k);
  if (!f) fail(`Unknown rule-set key '${k}'. Known: ${C.RULESET_FIELDS.map(x => x.key).join(", ")}`);
  exp.ruleset.values[k] = f.type === "bool" ? v === "true" : Number(v);
}
if (mapPath) {
  const t = read(mapPath), rows = C.effectiveRows(exp, C.parseResults(exp.source.text, { plateSize }));
  try {
    const r = C.applyTemplate(exp, rows, C.parseTemplate(t), { name: basename(mapPath), sha256: await C.sha256(t), importedAt: new Date().toISOString(), importedBy: actor });
    console.log(`Plate map ${basename(mapPath)}: ${r.changes.length} change(s)` + (r.issues.length ? `; not applied: ${r.issues.join("; ")}` : ""));
  } catch (e) { fail(`Plate map not applied: ${e.message}`, 1); }
}

const res = C.analyze(exp), s = res.summary;
console.log(`AssayLint ${C.APP_VERSION} · ${exp.source.name} · sha256 ${exp.source.sha256.slice(0, 16)}… · ${C.FORMATS[res.parsed.format]} · ${res.rows.length} rows`);
console.log(`Rule set ${C.rulesetId(exp.ruleset)}${C.rulesetChanges(exp.ruleset).length ? " (modified)" : ""}\n`);
for (const f of res.findings)
  console.log(`[${f.severity.toUpperCase()}] ${f.title} — ${f.description}\n    ${f.rule} v${f.rule_version} · ${C.CATEGORY_LABEL[f.category]}${f.wells.length ? " · " + f.wells.join(", ") : ""}\n    evidence: ${f.evidence}\n    next: ${f.next_check}`);
console.log(`\nStatus: ${s.label}. High ${s.bySeverity.high || 0}, medium ${s.bySeverity.medium || 0}, low ${s.bySeverity.low || 0}, info ${s.bySeverity.info || 0}.`);
console.log(`Not assessed:\n${res.notAssessed.map(x => "  - " + x).join("\n") || "  (none)"}`);
console.log("AssayLint flags possible issues for review; it does not certify an experiment or its conclusions.");
if (out.report) writeFileSync(out.report, R.reportHtml(exp, res));
if (out.json) writeFileSync(out.json, R.structuredJson(exp, res));
if (out.wells) writeFileSync(out.wells, R.wellsCsv(res));
if (out.packet) writeFileSync(out.packet, R.packetJson(exp, res));
